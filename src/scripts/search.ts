interface SearchData {
  url: string;
  meta: { title: string };
  excerpt: string;
}
interface SearchIndex {
  search: (
    query: string,
  ) => Promise<{ results: Array<{ data: () => Promise<SearchData> }> }>;
}

const trigger =
  document.querySelector<HTMLButtonElement>("[data-search-open]")!;
const dialog = document.querySelector<HTMLDialogElement>("#site-search")!;
const input = dialog.querySelector<HTMLInputElement>("input")!;
const status = dialog.querySelector<HTMLElement>("[data-search-status]")!;
const results = dialog.querySelector<HTMLUListElement>(
  "[data-search-results]",
)!;
let index: Promise<SearchIndex> | undefined;
let revision = 0;
let debounce: ReturnType<typeof setTimeout>;

function openSearch() {
  if (!dialog.open) dialog.showModal();
  input.focus();
}

trigger.hidden = false;
trigger.addEventListener("click", openSearch);
dialog
  .querySelector("[data-search-close]")!
  .addEventListener("click", () => dialog.close());
dialog.addEventListener("close", () => trigger.focus());
dialog.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    event.preventDefault();
    dialog.close();
  }
});
document.addEventListener("keydown", (event) => {
  const target = event.target as HTMLElement;
  if (
    (event.ctrlKey || event.metaKey) &&
    event.key.toLowerCase() === "k" &&
    !target.closest('input, textarea, [contenteditable="true"]')
  ) {
    event.preventDefault();
    openSearch();
  }
});

input.addEventListener("input", () => {
  clearTimeout(debounce);
  const current = ++revision;
  const query = input.value.trim();
  results.replaceChildren();
  if (!query) {
    status.textContent = "Enter a word or phrase to search.";
    return;
  }
  status.textContent = "Searching…";
  debounce = setTimeout(async () => {
    try {
      // The sole index is generated by Starlight after the production build.
      const path = "/pagefind/pagefind.js";
      index ??= import(/* @vite-ignore */ path);
      const matches = await (await index).search(query);
      const pages = await Promise.all(
        matches.results.slice(0, 12).map((item) => item.data()),
      );
      if (current !== revision) return;
      for (const page of pages) {
        const item = document.createElement("li");
        const link = document.createElement("a");
        // Pagefind omits .html from file-format URLs; private S3 needs exact keys.
        const url = new URL(page.url, location.origin);
        if (url.pathname !== "/" && !url.pathname.endsWith(".html")) {
          url.pathname = url.pathname.replace(/\/$/, "") + ".html";
        }
        link.href = url.pathname + url.hash;
        link.textContent = page.meta.title;
        const excerpt = document.createElement("span");
        excerpt.textContent = new DOMParser().parseFromString(
          page.excerpt,
          "text/html",
        ).body.textContent;
        link.append(excerpt);
        item.append(link);
        results.append(item);
      }
      status.textContent = matches.results.length
        ? `${matches.results.length} result${matches.results.length === 1 ? "" : "s"}${matches.results.length > 12 ? ". Showing the first 12" : ""}.`
        : "No matching pages. Try another word, such as AWS or Python.";
    } catch {
      index = undefined;
      if (current !== revision) return;
      status.textContent = import.meta.env.DEV
        ? "Search is available after npm run build, then npm run preview."
        : "Search could not load. Try again, or browse the handbook.";
    }
  }, 180);
});
